/** Busca sem acento e sem maiúscula; todas as palavras precisam aparecer; quem casa no título vem primeiro. */
export function buscar(consulta: string): Topico[] {
  const termos = semAcento(consulta).split(/\s+/).filter(Boolean);
  if (!termos.length) return TOPICOS;
  const pontuados: { t: Topico; p: number }[] = [];
  for (const t of TOPICOS) {
    const titulo = semAcento(t.titulo);
    const tudo = semAcento([t.titulo, t.resumo, t.passos.join(' '), t.dica ?? '', t.palavras ?? '', t.funcao].join(' '));
    if (!termos.every((x) => tudo.includes(x))) continue;
    const p = termos.reduce((s, x) => s + (titulo.includes(x) ? 10 : 0) + (semAcento(t.funcao).includes(x) ? 5 : 0), 0);
    pontuados.push({ t, p });
  }
  return pontuados.sort((a, b) => b.p - a.p).map((x) => x.t);
}
